/**
 * Fisher-Yates array shuffle utility
 */
export function shuffleArray<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Generates a fresh, dynamic randomized quiz:
 * 1. Shuffles and samples 'count' questions from the full question bank.
 * 2. Shuffles the 4 answer choices (A, B, C, D) for every single selected question.
 * 3. Dynamically re-indexes the correctAnswer pointer so evaluation remains 100% mathematically accurate.
 * 4. Ensures no two quiz attempts are ever identical!
 */
export function generateRandomQuiz(
  pool: QuizQuestionData[] = QUIZ_QUESTIONS,
  count: number = 15
): QuizQuestionData[] {
  // 1. Shuffle the question pool and sample 'count' questions
  const shuffledPool = shuffleArray(pool);
  const selected = shuffledPool.slice(0, Math.min(count, pool.length));

  // 2. For each selected question, shuffle its options and recalculate correctAnswer index
  return selected.map((q) => {
    const originalCorrectText = q.options[q.correctAnswer];
    const shuffledOptions = shuffleArray(q.options) as [string, string, string, string];
    const newCorrectIndex = shuffledOptions.indexOf(originalCorrectText);

    return {
      ...q,
      options: shuffledOptions,
      correctAnswer: newCorrectIndex >= 0 ? newCorrectIndex : 0,
    };
  });
}
